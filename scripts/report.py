"""Writes docs/STATUS.md: the prototype acceptance test, computed from the files that hold the evidence.

  data/eval_set.json   your labels (expected style, whether a close match is known)
  data/runs/*.json     harness runs (style, picks, seconds, cost)
  data/review*.json    your false-match verdicts; matched to a run by its picks, so an unreviewed run shows as such

Run with `make report`. Never edit STATUS.md by hand.
"""
import glob, json, os, re, statistics

D = 'data/'
OUT = 'docs/STATUS.md'
PRIMARY = 'openai/gpt-5.6-luna'
MANUAL = [('Decision in under 60 s with the app', 'passed in live use, 2026-10-19 (user; decisions.md)', '✅'),
          ('Same records take at least 90 s manually', 'dropped by the user, 2026-10-19', '—'),
          ('Photographed-crate test', 'not done', '—')]

def reason(p): return p.split('] — ', 1)[-1]

def reviewed_by(run, reviews):
    """The review file whose verdicts were given on exactly this run's picks, as (name, {id: entry})."""
    rows = {r['id']: r for r in run['rows']}
    for name, entries in reviews:
        es = {e['id']: e for e in entries if e['model'] == run['model']}
        if es and set(es) == set(rows) and all(
                sorted(map(reason, e['picks'])) == sorted(p['reason'] for p in ((rows[i]['result'] or {}).get('picks') or []))
                for i, e in es.items()):
            return name, es
    return None, {}

def score(run, labels, reviews):
    rows = run['rows']
    ok = [r for r in rows if r['result']]
    scored = [r for r in ok if r['result']['style'] != 'Other/uncertain'       # accuracy is among specific styles,
              and labels.get(r['id'], {}).get('expected_style') not in (None, 'Other/uncertain')]   # as harness.report counts it
    wrong = [r for r in scored if r['result']['style'] != labels[r['id']]['expected_style']]
    no_close = [r for r in rows if labels.get(r['id'], {}).get('close_match_known') is False]
    review, verdicts = reviewed_by(run, reviews)
    false = [r for r in rows if verdicts.get(r['id'], {}).get('false_match')]
    secs = [r['seconds'] for r in rows]
    return {'n': len(rows), 'available': len(ok), 'specific': sum(r['result']['style'] != 'Other/uncertain' for r in ok),
            'right': len(scored) - len(wrong), 'scored': len(scored), 'wrong': wrong,
            'nothing_close': sum(1 for r in no_close if r['result'] and not r['result']['picks']), 'no_close': len(no_close),
            'review': review, 'false': false if review else None,
            'median': statistics.median(secs), 'max': max(secs), 'cost': sum(r['cost'] for r in rows) / len(rows)}

def name(r): return '%s — %s' % (r['artist'], r['title'])
def mark(ok): return '✅' if ok else '❌'

def main():
    labels = {e['id']: e for e in json.load(open(D + 'eval_set.json', encoding='utf-8'))}
    files = sorted(glob.glob(D + 'review*.json'), key=lambda f: int(re.sub(r'\D', '', os.path.basename(f)) or 1))
    reviews = [(os.path.basename(f), json.load(open(f, encoding='utf-8'))) for f in files]
    runs = sorted(glob.glob(D + 'runs/*.json'), key=lambda f: f[-20:])       # filenames end in the run's timestamp
    scores = [(os.path.basename(f), json.load(open(f, encoding='utf-8'))) for f in runs]
    scores = [(f, run['model'], score(run, labels, reviews)) for f, run in scores]
    latest = {}
    for f, model, s in scores: latest[model] = (f, s)

    out = ['# Crate Digger status', '',
           'Generated by `make report` from `data/eval_set.json`, `data/runs/` and `data/review*.json`. Do not edit by hand. Every run is scored against the current labels.', '',
           '## Prototype acceptance test', '']
    for model in sorted(latest, key=lambda m: m != PRIMARY):
        f, s = latest[model]
        out += ['### %s%s' % (model, ' (primary, used by the app)' if model == PRIMARY else ' (fallback)'), '',
                'Latest run `%s`, reviewed in %s.' % (f, '`%s`' % s['review'] if s['review'] else '**no review yet**'), '',
                '| Criterion | Target | Result | |', '| --- | --- | --- | --- |',
                '| Records with a specific style | 18 of 20 | %d of %d | %s |' % (s['specific'], s['n'], mark(s['specific'] >= 18)),
                '| Style accuracy | 90%% | %d of %d (%.0f%%) | %s |' % (s['right'], s['scored'], 100 * s['right'] / s['scored'], mark(s['right'] >= 0.9 * s['scored'])),
                ('| False close matches | at most 15%% | %d of %d (%.0f%%) | %s |' % (len(s['false']), s['n'], 100 * len(s['false']) / s['n'], mark(len(s['false']) <= 0.15 * s['n']))
                 if s['false'] is not None else '| False close matches | at most 15% | needs review | — |')]
        out += ['| %s | | %s | %s |' % m for m in MANUAL] if model == PRIMARY else []
        out += ['', '- Style wrong: %s' % ('; '.join('%s (label %s, model %s)' % (name(r), labels[r['id']]['expected_style'], r['result']['style']) for r in s['wrong']) or 'none')]
        if s['false'] is not None: out += ['- False matches: %s' % ('; '.join(map(name, s['false'])) or 'none')]
        out += ['- Nothing close answered for %d of %d records with no close match known' % (s['nothing_close'], s['no_close']),
                '- Available %d of %d; median %.1f s, slowest %.1f s; US$%.4f per record' % (s['available'], s['n'], s['median'], s['max'], s['cost']), '']

    out += ['## All runs', '', '| Run | Style | False matches | Nothing close | Median | Per record |', '| --- | --- | --- | --- | --- | --- |']
    for f, model, s in scores:
        out.append('| `%s` | %d/%d | %s | %d/%d | %.1f s | US$%.4f |' % (
            f, s['right'], s['scored'], '%d/%d (%s)' % (len(s['false']), s['n'], s['review']) if s['false'] is not None else 'not reviewed',
            s['nothing_close'], s['no_close'], s['median'], s['cost']))
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, 'w', encoding='utf-8').write('\n'.join(out) + '\n')
    print('wrote', OUT)

if __name__ == '__main__':
    main()
